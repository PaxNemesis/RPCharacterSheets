/** Every spell entry; a spell printed in more than one book has an entry for each. */
export const SPELLS: SpellData[] = Object.entries(ROWS).flatMap(([book, rows]) =>
  rows.map(([name, page, cost, rng, aoe, pow, up, off]) => ({
    name,
    book: book as BookId,
    page,
    cost,
    rng,
    aoe,
    pow,
    up,
    off,
  })),
);

/** Names of the spells in the books the character uses, for suggestions. */
export const spellNames = (settings: IkSettings) =>
  [...new Set(SPELLS.filter((spell) => bookEnabled(settings, spell.book)).map((spell) => spell.name))].sort(
    compareNames,
  );

/** The spell's entry in the first of the character's books that has it. */
export const findSpell = (name: string, settings: IkSettings) => {
  const key = name.trim().toLowerCase();
  return SPELLS.find((spell) => spell.name.toLowerCase() === key && bookEnabled(settings, spell.book));
};

const number = (value: string) => (/^\d+/.test(value) ? Number.parseInt(value, 10) : null);

/**
 * A spell's numbers as sheet fields. COST "1+" (Locomotion, the caster picks how much) becomes 1, and
 * "—" or "*" become blank; the description is left for the player.
 */
export const spellFields = (spell: SpellData): Omit<IkSpell, 'description'> => ({
  name: spell.name,
  cost: number(spell.cost),
  rng: spell.rng,
  aoe: spell.aoe,
  pow: number(spell.pow),
  up: spell.up,
  off: spell.off,
  page: bookRef(spell.book, spell.page),
});
